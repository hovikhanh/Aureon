#!/usr/bin/env python3
"""Generate `packages/shared-types/src/generated.ts` from the FastAPI OpenAPI (T-605, R-DEC-19).

Stdlib only. Reads `create_app().openapi()` in-process (no server) and emits:
  * one `export type <Schema> = …` per `components.schemas` entry (objects as `{ … }` literals,
    enums as string unions, `anyOf` as unions, `$ref` by name);
  * `ApiOperations`: `"<METHOD> <path>"` → `{ request; response }` (JSON body schemas, `void`
    when none) so the FE / mock router can type calls by endpoint.
Output is deterministic (sorted); `--check` exits 1 when the committed file differs (drift).

Run from repo root:
    PYTHONPATH=apps/api/src:apps/api .venv/bin/python scripts/gen_shared_types.py [--check]
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "packages" / "shared-types" / "src" / "generated.ts"
HEADER = (
    "/* eslint-disable */\n"
    "/**\n"
    " * GENERATED by scripts/gen_shared_types.py from the FastAPI OpenAPI — DO NOT EDIT.\n"
    " * Regenerate: PYTHONPATH=apps/api/src:apps/api .venv/bin/python scripts/gen_shared_types.py\n"
    " * Drift is checked by apps/api/tests/contract/test_shared_types.py (TC-M11-08).\n"
    " */\n"
)
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
PRIMITIVE = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
             "null": "null"}  # fmt: skip


def ref_name(ref: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", ref.rsplit("/", 1)[-1])


def union(parts: list[str]) -> str:
    seen = list(dict.fromkeys(parts))
    return seen[0] if len(seen) == 1 else " | ".join(seen)


def literal(v: Any) -> str:
    return json.dumps(v, ensure_ascii=False)


def prop_key(name: str) -> str:
    return name if IDENT.match(name) else literal(name)


def ts(schema: dict[str, Any] | bool, indent: str = "") -> str:
    """TypeScript type expression for one JSON-Schema node (OpenAPI 3.1 subset FastAPI emits)."""
    if schema is True or schema == {}:
        return "unknown"
    if schema is False:
        return "never"
    if not isinstance(schema, dict):
        raise TypeError(f"unsupported JSON-Schema node: {schema!r}")
    if "$ref" in schema:
        return ref_name(schema["$ref"])
    if "const" in schema:
        return literal(schema["const"])
    if "enum" in schema:
        return union([literal(v) for v in schema["enum"]])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return union([wrap(ts(s, indent)) for s in schema[key]])
    if "allOf" in schema:
        return " & ".join(wrap(ts(s, indent)) for s in schema["allOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return union([ts({**schema, "type": k}, indent) for k in kind])
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(s, indent) for s in schema["prefixItems"]) + "]"
        return f"{wrap(ts(schema.get('items', True), indent))}[]"
    if kind == "object" or "properties" in schema:
        return obj(schema, indent)
    return PRIMITIVE.get(str(kind), "unknown")


def wrap(t: str) -> str:
    return f"({t})" if " | " in t or " & " in t else t


def obj(schema: dict[str, Any], indent: str) -> str:
    props: dict[str, Any] = schema.get("properties", {})
    extra = schema.get("additionalProperties")
    if not props:
        if extra in (None, True, {}):
            return "Record<string, unknown>"
        return f"Record<string, {ts(extra, indent)}>" if extra is not False else "{}"
    required = set(schema.get("required", []))
    inner = indent + "  "
    lines = [
        f"{inner}{prop_key(k)}{'' if k in required else '?'}: {ts(v, inner)};"
        for k, v in props.items()
    ]
    if extra not in (None, False):
        lines.append(f"{inner}[key: string]: unknown;")
    return "{\n" + "\n".join(lines) + f"\n{indent}}}"


def json_schema(content: dict[str, Any] | None) -> dict[str, Any] | None:
    for mime, media in (content or {}).items():
        if "json" in mime and "schema" in media:
            return media["schema"]  # type: ignore[no-any-return]
    return None


def operations(paths: dict[str, Any]) -> list[str]:
    lines = []
    for path in sorted(paths):
        for method in sorted(paths[path]):
            op = paths[path][method]
            if not isinstance(op, dict):
                continue
            req = json_schema(op.get("requestBody", {}).get("content"))
            ok = next((r for c, r in sorted(op.get("responses", {}).items())
                       if c.startswith("2")), {})  # fmt: skip
            res = json_schema(ok.get("content"))
            lines.append(
                f"  {literal(method.upper() + ' ' + path)}: {{\n"
                f"    request: {ts(req, '    ') if req else 'void'};\n"
                f"    response: {ts(res, '    ') if res else 'void'};\n  }};"
            )
    return lines


def render(spec: dict[str, Any]) -> str:
    out = [HEADER]
    for name in sorted(spec.get("components", {}).get("schemas", {})):
        s = spec["components"]["schemas"][name]
        out.append(f"export type {ref_name(name)} = {ts(s)};\n")
    out.append(
        "export interface ApiOperations {\n" + "\n".join(operations(spec["paths"])) + "\n}\n"
    )
    out.append("export type ApiOperationKey = keyof ApiOperations;\n")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    from app.main import create_app

    text = render(create_app().openapi())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"✗ {OUT.relative_to(ROOT)} is stale — run scripts/gen_shared_types.py")
            return 1
        print("✔ shared types up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count('export type')} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
